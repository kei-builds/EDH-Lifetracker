// Tool sheets: Tax, Mana (with storm) and Counters (with the rad reminder and Concede), and the chips and tiles they feed.
export default async ({ page, app, evidence, assert }) => {
  await app.newGame({ players: 2, names: ["Atraxa, Praetors' Voice", 'Krenko, Mob Boss'] });
  const plusIn = (scope, n = 0) => scope.locator('.ctr').nth(n).getByRole('button', { name: '+', exact: true });

  await app.openTool(0, 'tax');
  assert.equal(await app.sheet(0).locator('h3').textContent(), 'Commander tax');
  await plusIn(app.sheet(0)).tap();
  await plusIn(app.sheet(0)).tap();
  assert.equal(await app.sheet(0).locator('.ctr b').textContent(), '4', 'tax climbs in steps of 2');
  assert.deepEqual((await app.game()).players[0].tax, [4, 0]);
  await evidence.shot('tax-sheet');
  await app.sheet(0).getByRole('button', { name: 'Done' }).tap();
  assert.equal(await app.sheet(0).count(), 0);
  const shown = sel => app.panel(0).locator(sel).filter({ visible: true });
  assert.equal(await shown('.a-tax .vals').textContent(), '4', 'Companion shows the tax on the Tax tile');
  assert.equal(await shown('.badges > span').count(), 0, 'Companion shows no chips; the tiles carry the values');
  const taxTile = await app.panel(0).locator('.a-tax').boundingBox(), manaTile = await app.panel(0).locator('.a-mana').boundingBox();
  assert.ok(Math.abs(taxTile.height - manaTile.height) < 1 && Math.abs(taxTile.width - manaTile.width) < 1, "the Tax tile keeps the empty Mana tile's size while it shows a number");
  evidence.note('tax 4');

  await app.openTool(0, 'mana');
  const symbol = c => `https://svgs.scryfall.io/card-symbols/${c}.svg`;
  const pips = app.sheet(0).locator('.ctr img.pip');
  assert.deepEqual(await pips.evaluateAll(es => es.map(e => [e.alt, e.src])), ['W', 'U', 'B', 'R', 'G', 'C'].map(c => [c, symbol(c)]),
    'the six pool counters show Scryfall\'s mana symbols, in WUBRGC order');
  assert.ok(await pips.evaluateAll(es => Promise.all(es.map(e => e.decode())).then(() => true, () => false)), 'and every symbol loaded');
  const storm = app.sheet(0).locator('.storm');
  await storm.tap();
  await storm.tap();
  assert.equal(await storm.locator('b').textContent(), '2');
  await plusIn(app.sheet(0), 0).tap();
  let g = await app.game();
  assert.equal(g.storm, 2);
  assert.equal(g.players[0].mana.W, 1);
  await evidence.shot('mana-sheet');
  await app.sheet(0).getByRole('button', { name: 'Done' }).tap();
  assert.equal(await shown('.a-mana .vals .v').count(), 1, 'the Mana tile shows the one floating color');
  assert.equal(await shown('.a-mana .vals .v').textContent(), '1', 'with its count');
  assert.equal(await shown('.a-mana .vals .v img.pip').getAttribute('src'), symbol('W'), 'behind the white mana symbol');
  await app.openTool(0, 'mana');
  await app.sheet(0).getByRole('button', { name: 'Empty pool' }).tap();
  assert.equal((await app.game()).players[0].mana.W, 0);
  await app.sheet(0).getByRole('button', { name: 'Done' }).tap();
  assert.equal(await shown('.a-mana .vals').count(), 0, 'an empty pool leaves the Mana tile bare');
  await app.$('pass').tap();
  g = await app.game();
  assert.equal(g.storm, 0, 'passing the turn resets storm');
  assert.equal(g.active, 1);
  await app.$('undo').tap();
  g = await app.game();
  assert.equal(g.storm, 2, 'undoing the pass brings the storm count back with the rest of the game');
  assert.equal(g.active, 0);
  await app.$('pass').tap();
  g = await app.game();
  assert.equal(g.storm, 0);
  assert.equal(g.active, 1);
  evidence.note('storm counted, reset on turn pass, and restored by undoing the pass');

  await app.openTool(1, 'counters');
  assert.equal(await app.sheet(1).locator('h3').textContent(), 'Counters');
  for (let i = 0; i < 3; i++) await plusIn(app.sheet(1), 0).tap();
  await plusIn(app.sheet(1), 1).tap();
  g = await app.game();
  assert.equal(g.players[1].counters.poison, 3);
  assert.equal(g.players[1].counters.energy, 1);
  await evidence.shot('counters-sheet');
  await app.sheet(1).getByRole('button', { name: 'What rad counters do' }).tap();
  await app.$('radInfo').waitFor({ state: 'visible' });
  assert.match(await app.$('radText').textContent(), /rad counters/);
  await evidence.shot('rad-reminder');
  await app.$('radClose').tap();
  await app.$('radInfo').waitFor({ state: 'hidden' });
  await app.sheet(1).getByRole('button', { name: 'Done' }).tap();
  const tile = await app.panel(1).locator('.a-counters').textContent();
  assert.match(tile, /3/, 'the Counters tile lists poison');
  assert.match(tile, /1/, 'and energy');
  assert.ok(await app.panel(1).locator('.a-counters > svg').isVisible(), 'Companion keeps the Counters icon while the tile lists counters');
  const header = await app.tileHeader(1, 'counters');
  assert.ok(header.labelUnderIcon && header.rowUnderLabel, 'the label sits under the icon and the counter rows under the label');
  assert.ok(Math.abs(header.iconTop - header.taxIconTop) <= 2, `the Counters header starts ${header.iconTop}px down its tile, the Tax tile's ${header.taxIconTop}px`);
  await evidence.shot('counters-tile');
  evidence.note('poison 3, energy 1, rad reminder opened and closed');

  await app.openTool(1, 'counters');
  await app.hold(plusIn(app.sheet(1), 0), 1400);
  g = await app.game();
  assert.ok(g.players[1].counters.poison >= 10, `a hold reaches ten poison (got ${g.players[1].counters.poison})`);
  assert.equal(g.players[1].out.cause, 'poison');
  assert.equal(await app.sheet(1).getByRole('button', { name: 'Out' }).isDisabled(), true, 'Concede becomes a disabled Out');
  await app.sheet(1).getByRole('button', { name: 'Done' }).tap();
  assert.match(await app.panel(1).locator('.out').textContent(), /poison/);
  await evidence.shot('poisoned-out');

  // Brought back past ten poison the player stays in, and Concede reads Out: it records what their numbers show.
  await app.panel(1).getByRole('button', { name: 'Bring back' }).tap();
  assert.equal((await app.game()).players[1].out, null, 'Bring back puts the player back in');
  await app.openTool(1, 'counters');
  await plusIn(app.sheet(1), 0).tap();
  assert.equal((await app.game()).players[1].out, null, 'one more poison past ten crosses nothing');
  assert.equal(await app.sheet(1).getByRole('button', { name: 'Concede' }).count(), 0, 'past a line there is no Concede');
  assert.equal(await app.sheet(1).getByRole('button', { name: 'Out' }).isDisabled(), false, 'but an Out to tap');
  await evidence.shot('out-by-hand-offered');
  await app.sheet(1).getByRole('button', { name: 'Out' }).tap();
  g = await app.game();
  assert.equal(g.players[1].out.cause, 'poison', 'Out by hand records the cause the numbers show');
  assert.equal(await app.sheet(1).count(), 0, 'and closes the sheet');
  evidence.note('brought back past ten poison, then put out by hand', { cause: g.players[1].out.cause });

  await app.openTool(0, 'counters');
  await app.sheet(0).getByRole('button', { name: 'Concede' }).tap();
  g = await app.game();
  assert.equal(g.players[0].out.cause, 'concede');
  assert.match(await app.panel(0).locator('.out').textContent(), /conceded/);
  await evidence.shot('conceded');
  await evidence.storeDump('both-out');
  evidence.note('poison knockout and concession recorded', { outs: g.players.map(p => p.out && p.out.cause) });
};
